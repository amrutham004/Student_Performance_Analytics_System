import pandas as pd
import numpy as np

df = pd.read_csv("student_data.csv")
print(df)

print("\n-------------------------First Five Records-------------------------------")
print(df.head())

print("\n-------------------------Dataset Information-------------------------------")
print(df.info())

print("\n Total Number of Students:", len(df))

subs = ["Mathematics ", "Python programming", "Engineering Drawing"]
df["Total Marks"] = df[subs].sum(axis=1)
print(df["Total Marks"])
df["Average Marks"] = df[subs].mean(axis=1).round(2)
print(df["Average Marks"])

# Function to calculate grades
def calculate_grade(average):
  if average >= 90:
    return "A+"
  elif average >= 80:
    return "A"
  elif average >= 70:
    return "B+"
  elif average >= 60:
    return "B"
  elif average >= 50:
    return "C"
  else:
    return "F"

df["Grade"] = df["Average Marks"].apply(calculate_grade)
print(df["Grade"])

# Function to determine whether the student is pass/fail
def calculate_result(row):
    for subject in subs:
        if row[subject] < 40:
            return "Fail"
    return "Pass"
df["Result"] = df.apply(calculate_result, axis=1)
print(df["Result"])

# Clean column names by stripping leading/trailing whitespaces
df.columns = df.columns.str.strip()

print("\n------------------Student Performance------------------------------")
print(df[["Student ID", "Name", "Total Marks",
         "Average Marks", "Grade", "Result"]].to_string(index=False)
)

print("\n-------------------Overall Performance--------------------------")
total_no_of_students = len(df)

passed_students = (df["Result"] == "Pass").sum()
failed_students = (df["Result"] == "Fail").sum()

class_average = np.mean(df["Average Marks"])
highest_average = np.max(df["Average Marks"])
lowest_average = np.min(df["Average Marks"])

print("Total Number of Students:", total_no_of_students)
print("Number of Students Passed:", passed_students)
print("Number of Students Failed:", failed_students)
print("Class Average Marks:", round(class_average, 2))
print("Highest Average Marks:", highest_average)
print("Lowest Average Marks", lowest_average)

print("\n-----------------Subject Wise Performance Analysis----------------------")
# Clean the subject names in the list to match the stripped DataFrame column names
cleaned_subs = [s.strip() for s in subs]

for subject in cleaned_subs:
    marks = df[subject].to_numpy()

    average = np.mean(marks)
    highest = np.max(marks)
    lowest = np.min(marks)

    print("\nSubject Name:", subject)
    print("Average Marks:", round(average, 2))
    print("Highest Marks:", highest)
    print("Lowest Marks:", lowest)

    subject_pass = np.sum(marks >= 40)
    subject_fail = np.sum(marks < 40)

    print("Students Passed:", subject_pass)
    print("Students Failed:", subject_fail)

print("\n-------------------Data Visualization------------------------")
import matplotlib.pyplot as plt

# Clean the subject names to match the stripped DataFrame column names
cleaned_subs = [s.strip() for s in subs]

# Subject Wise Average Marks
subject_averages = [
    np.mean(df[subject]) for subject in cleaned_subs
]

plt.figure(figsize=(8, 5))
plt.bar(cleaned_subs, subject_averages)

plt.title("Subject-wise Average Marks")
plt.xlabel("Subjects")
plt.ylabel("Average Marks")
plt.ylim(0, 100)
plt.tight_layout()
plt.show()

result_counts = df["Result"].value_counts()

plt.figure(figsize=(6, 6))
plt.pie(
    result_counts.values,
    labels=result_counts.index,
    autopct="%1.1f%%",
    startangle=90
)

plt.title("Student Pass/Fail Distribution")
plt.tight_layout()
plt.show()

top_five = df.sort_values(
    by="Average Marks",
    ascending=False
).head(5)

plt.figure(figsize=(8, 5))
plt.bar(top_five["Name"], top_five["Average Marks"])

plt.title("Top Five Student Performers")
plt.xlabel("Student Name")
plt.ylabel("Average Marks")
plt.ylim(0, 100)
plt.xticks(rotation=30, ha="right")
plt.tight_layout()
